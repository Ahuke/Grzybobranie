def parse_logged_in_html(html_path: Path) -> dict[str, dict[str, str | float]]:
    """
    Parsuje zapisany lokalnie plik HTML pobrany po zalogowaniu na grzyby.pl
    i wyciąga współrzędne (lat, lon), nazwę miejscowości/powiatu oraz kod TERYT.
    """
    content = html_path.read_text(encoding="utf-8", errors="replace")
    blocks = re.findall(
        r'id="(DG\d+)"(.*?)(?=<div class="w3-row-padding[^>]*doniesienie-blok"|<footer|$)',
        content,
        re.S,
    )
    mapping: dict[str, dict[str, str | float]] = {}
    for report_id, block in blocks:
        gmap = re.search(r"maps/place/([0-9.-]+)\+([0-9.-]+)/[^>]*>(.*?)</a>", block, re.S)
        place_id_m = re.search(r"historyczne_z_miejsca/(\d+)/", block)
        place_id = place_id_m.group(1) if place_id_m else ""
        if gmap:
            lat = float(gmap.group(1))
            lon = float(gmap.group(2))
            loc_label = re.sub(r"&nbsp;|\s+", " ", gmap.group(3)).strip()
            teryt = resolve_teryt(loc_label)
            mapping[report_id] = {
                "place_id": place_id,
                "locality_logged_in": loc_label,
                "powiat_teryt": teryt,
                "lat": lat,
                "lon": lon,
            }
    return mapping


def main() -> None:
    parser = argparse.ArgumentParser(description="Audyt próbki raportów z grzyby.pl ([GRZ-03] #3)")
    parser.add_argument(
        "--logged-in-html",
        type=Path,
        default=DEFAULT_LOGGED_HTML,
        help="Ścieżka do lokalnie zapisanego pliku HTML po zalogowaniu",
    )
    args = parser.parse_args()

    if args.logged_in_html and args.logged_in_html.exists():
        logged_in_map = parse_logged_in_html(args.logged_in_html)
        raw_map_out = Path(__file__).resolve().parent.parent / "data" / "raw" / "place_id_to_locality.json"
        raw_map_out.parent.mkdir(parents=True, exist_ok=True)
        place_dict = {
            str(v["place_id"]): {
                "locality_logged_in": v["locality_logged_in"],
                "powiat_teryt": v["powiat_teryt"],
                "lat": v["lat"],
                "lon": v["lon"],
            }
            for v in logged_in_map.values()
            if v.get("place_id")
        }
        raw_map_out.write_text(json.dumps(place_dict, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"Zapisano lokalny słownik place_id -> (miejscowość, TERYT, lat, lon) dla {len(place_dict)} unikalnych miejsc w: {raw_map_out}")

    out_path = Path(__file__).resolve().parent.parent / "data" / "sample" / "reports_audit_52_ds.csv"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = [
        "report_id",
        "source_url",
        "harvest_date",
        "publication_date",
        "publication_time",
        "pub_delay_days",
        "voivodeship",
        "place_id",
        "locality_logged_in",
        "powiat_teryt",
        "lat",
        "lon",
        "location_in_public_text",
        "yield_pcs_per_h",
        "total_pieces",
        "harvest_duration_h",
        "pickers_count",
        "dominant_species",
        "species_latin_tags",
        "forest_type_hint",
        "is_zero_harvest",
        "is_poor_harvest_comment",
    ]

    with out_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in AUDITED_REPORTS:
            row_copy = dict(row)
            row_copy["source_url"] = f"{BASE_URL}#{row['report_id']}"
            writer.writerow(row_copy)

    total = len(AUDITED_REPORTS)
    unique_powiats = sorted({r["powiat_teryt"] for r in AUDITED_REPORTS if r["powiat_teryt"]})
    has_public_loc = sum(1 for r in AUDITED_REPORTS if r["location_in_public_text"])
    has_logged_loc = sum(1 for r in AUDITED_REPORTS if r["powiat_teryt"] != "")
    print(f"Zapisano {total} rekordów do: {out_path}")
    print(f"- Lokalizacja bez logowania (w treści): {has_public_loc}/{total} ({has_public_loc/total:.1%})")
    print(f"- Lokalizacja + GPS po zalogowaniu:     {has_logged_loc}/{total} ({has_logged_loc/total:.1%}) w {len(unique_powiats)} powiatach: {unique_powiats}")


if __name__ == "__main__":
    main()
